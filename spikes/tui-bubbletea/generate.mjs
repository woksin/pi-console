// Deliberately small generator for the exact JSON Schema vocabulary of API v0.
// Run from this directory: node generate.mjs (no third-party tools).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const schema = JSON.parse(readFileSync('../../docs/api/schemas/api.json', 'utf8'));
const name = s => s.replace(/(^|[^a-zA-Z0-9])([a-zA-Z0-9])/gu, (_, _prefix, c) => c.toUpperCase()).replace(/Id(s)?$/u, (_, plural) => `ID${plural || ''}`);
function type(s) {
  if (s.$ref) return name(s.$ref.split('/').at(-1));
  if (s.anyOf) return `*${type(s.anyOf.find(x => x.type !== 'null'))}`;
  if (s.const !== undefined) return typeof s.const === 'string' ? 'string' : 'int';
  switch (s.type) {
    case 'string': return 'string';
    case 'integer': return 'int';
    case 'number': return 'float64';
    case 'boolean': return 'bool';
    case 'array': return `[]${type(s.items)}`;
    case 'object': return `struct {\n${Object.entries(s.properties).map(([k, v]) => `${name(k)} ${type(v)} \`json:"${k}${s.required?.includes(k) ? '' : ',omitempty'}"\``).join('\n')}\n}`;
    default: throw new Error(`Unsupported schema: ${JSON.stringify(s)}`);
  }
}
let output = '// Code generated by node generate.mjs from docs/api/schemas/api.json; DO NOT EDIT.\npackage api\nimport ("encoding/json"; "fmt")\n';
for (const [k, v] of Object.entries(schema.$defs)) {
  if (k !== 'event') output += `type ${name(k)} ${type(v)}\n`;
}
output += 'type Event struct { Seq int `json:"seq"`; Type string `json:"type"`; OccurredAt string `json:"occurredAt"`; Payload json.RawMessage `json:"payload"` }\n';
output += 'func (e Event) DecodePayload() (any, error) { var target any; switch e.Type {\n';
for (const variant of schema.$defs.event.oneOf) output += `case ${JSON.stringify(variant.properties.type.const)}: target = new(${type(variant.properties.payload)})\n`;
output += 'default: return nil, fmt.Errorf("unknown event %q", e.Type) }; err := json.Unmarshal(e.Payload, target); return target, err }\n';
mkdirSync('api', { recursive: true });
output = execFileSync('gofmt', [], { input: output, encoding: 'utf8' });
if (process.argv.includes('--check')) {
  if (readFileSync('api/generated.go', 'utf8') !== output) throw new Error('Generated API types are stale; run node generate.mjs');
  console.log('Generated API types are current');
} else {
  writeFileSync('api/generated.go', output);
  console.log('Generated api/generated.go');
}
