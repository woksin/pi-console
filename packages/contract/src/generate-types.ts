import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { apiV0Schema, apiV1Schema, type JsonSchemaDocument } from './api.ts';
import { catalogue } from './catalogue.ts';
import type { Schema } from './schema-dsl.ts';

const pascal = (name: string) => name.replace(/(^|[.\-_ ])(\w)/g, (_, __, letter: string) => letter.toUpperCase());
const literal = (value: unknown) => JSON.stringify(value).replaceAll('"', "'");

function typeOf(schema: Schema): string {
  if (typeof schema.$ref === 'string') return pascal(schema.$ref.replace(/^.*#\/\$defs\//, ''));
  const alternatives = (schema.anyOf ?? schema.oneOf) as Schema[] | undefined;
  if (alternatives) return alternatives.map(typeOf).join(' | ');
  if (Object.hasOwn(schema, 'const')) return literal(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(literal).join(' | ');
  return typeOfPlain(schema);
}

function typeOfPlain(schema: Schema): string {
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${wrap(typeOf(schema.items as Schema))}[]`;
    case 'object': return typeOfObject(schema);
    default: return 'unknown';
  }
}

const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name));
const wrap = (type: string) => (type.includes(' | ') ? `(${type})` : type);

function typeOfObject(schema: Schema): string {
  const properties = schema.properties as Record<string, Schema> | undefined;
  if (!properties) return 'Record<string, unknown>';
  const required = new Set(schema.required as string[] | undefined);
  const members = Object.entries(properties).map(([name, value]) => `${key(name)}${required.has(name) ? '' : '?'}: ${typeOf(value)}`);
  return `{ ${members.join('; ')} }`;
}

function declare(name: string, schema: Schema) {
  return `export type ${pascal(name)} = ${typeOf(schema)};`;
}

const banner = (source: string) => `// @generated by packages/contract/src/generate-types.ts from ${source}. Do not edit; run \`npm run generate -w @pi-console/contract\`.\n`;

export function apiTypes(document: JsonSchemaDocument, source: string): string {
  const lines = Object.entries(document.$defs).map(([name, schema]) => declare(name, schema));
  return `${banner(source)}\n${lines.join('\n')}\n`;
}

export function catalogueTypes(): string {
  const payloads = catalogue.map(definition => declare(`${definition.type}Payload`, definition.payload));
  const map = catalogue.map(definition => `  ${definition.type}: ${definition.type}Payload;`);
  return `${banner('the event catalogue in catalogue.ts')}\n${payloads.join('\n')}\n\nexport interface EventPayloads {\n${map.join('\n')}\n}\n`;
}

export function generatedFiles(): Record<string, string> {
  return {
    'api-v0.ts': apiTypes(apiV0Schema, 'docs/api/schemas/api.json'),
    'api-v1.ts': apiTypes(apiV1Schema, 'apiV1Schema in api.ts'),
    'events.ts': catalogueTypes(),
  };
}

const directory = fileURLToPath(new URL('./generated/', import.meta.url));

/** Names of generated files whose committed content differs from a fresh generation. */
export function staleFiles(): string[] {
  return Object.entries(generatedFiles()).filter(([name, content]) => {
    try { return readFileSync(resolve(directory, name), 'utf8') !== content; } catch { return true; }
  }).map(([name]) => name);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) { console.error(`Generated contract types are stale: ${stale.join(', ')}. Run npm run generate -w @pi-console/contract`); process.exit(1); }
    console.log('Generated contract types are up to date.');
  } else {
    mkdirSync(directory, { recursive: true });
    for (const [name, content] of Object.entries(generatedFiles())) writeFileSync(resolve(directory, name), content);
  }
}

